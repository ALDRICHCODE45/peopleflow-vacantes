import { afterEach, expect, it, vi } from "vitest";
import { act, cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import "@testing-library/jest-dom/vitest";
import { BoardSkeleton } from "./board-states";
import { BoardColumns } from "./board-columns";
import { CandidateSheet } from "./candidate-sheet";
import { boardFixture, detailFixture, historyFixture, vacancyId } from "./board-fixture";
import { loadHistoryAction, loadParticipationAction } from "./actions";
import type { History, Result } from "./model";
vi.mock("./actions", () => ({ loadHistoryAction: vi.fn(), loadParticipationAction: vi.fn() }));
vi.mock("@/components/feedback/notify", () => ({ notifyActionResult: vi.fn() }));
afterEach(() => { cleanup(); vi.resetAllMocks(); });
const slots = (root: Element, selector: string) => [...root.querySelectorAll(selector)].map(node => node.getAttribute("data-slot"));
it("matches a real draggable card's slot sequence and avatar/menu/footer geometry", async () => {
  const board = boardFixture();
  const skeleton = render(<BoardSkeleton columnCount={board.stages.length + 1} />);
  const loaded = render(<BoardColumns board={board} pending={new Set()} locked={false} notices={{}} onMove={vi.fn()} onDetail={vi.fn()} onDisposition={vi.fn()} />);
  await act(async () => {});
  const loadingCard = skeleton.container.querySelector('[data-slot="card"]')!;
  const realCard = loaded.container.querySelector('[data-slot="card"]')!;
  const selector = '[data-slot^="card"], [data-slot="avatar"], [data-slot="separator"]';
  expect(slots(loadingCard, selector)).toEqual(slots(realCard, selector));
  expect(skeleton.container.querySelectorAll('.stage-column')).toHaveLength(board.stages.length + 1);
  expect(loadingCard.querySelector('[data-slot="avatar"]')).toHaveClass("size-8");
  expect(loadingCard.querySelector('[data-slot="card-action"] [data-slot="skeleton"]')).toHaveClass("size-10");
  expect(loadingCard.querySelector('[data-slot="card-footer"] [data-slot="skeleton"]')).toHaveClass("h-4");
  const cv = realCard.querySelector('[data-slot="card-footer"] span')!;
  expect(cv).not.toHaveClass("rounded-md", "bg-muted/60");
});
it("mirrors each sheet tab while waiting, then keeps the CV Item slots when loaded", async () => {
  let resolve!: (value: Result<History>) => void;
  vi.mocked(loadParticipationAction).mockResolvedValue({ ok: true, data: detailFixture() });
  vi.mocked(loadHistoryAction).mockReturnValue(new Promise(yes => { resolve = yes; }));
  const board = boardFixture();
  render(<CandidateSheet vacancyId={vacancyId} item={board.participations[0]} board={board} onClose={vi.fn()} />);
  const sheet = await screen.findByRole("dialog", { name: "Ana Pérez" });
  const summary = sheet.querySelector('[data-pf-detail-skeleton="summary"]')!;
  expect(summary.querySelectorAll('dl dt')).toHaveLength(10);
  expect(summary.querySelectorAll('section')).toHaveLength(4);
  const cvSlots = slots(summary, '[data-slot^="item"]');
  await act(async () => { fireEvent.click(within(sheet).getByRole("tab", { name: /Respuestas/ })); });
  expect(sheet.querySelectorAll('[data-pf-detail-skeleton="answers"] dl dt')).toHaveLength(2);
  await act(async () => { fireEvent.click(within(sheet).getByRole("tab", { name: /Historial/ })); });
  expect(sheet.querySelectorAll('[data-pf-detail-skeleton="history"] ol li')).toHaveLength(1);
  await act(async () => resolve({ ok: true, data: historyFixture() }));
  await act(async () => { fireEvent.click(within(sheet).getByRole("tab", { name: "Resumen" })); });
  expect(sheet.querySelector('[data-pf-detail-skeleton]')).toBeNull();
  expect(sheet.querySelectorAll('dl dt')).toHaveLength(10);
  expect(slots(sheet, '[data-slot^="item"]')).toEqual(cvSlots);
  expect(within(sheet).getByRole("link", { name: "Descargar CV" }).closest('[data-slot="item-actions"]')).not.toBeNull();
});
