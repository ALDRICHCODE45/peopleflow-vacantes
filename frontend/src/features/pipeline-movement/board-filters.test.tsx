import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import "@testing-library/jest-dom/vitest";
import { MovementBoard } from "./board";
import { boardFixture } from "./board-fixture";
import { loadBoardAction } from "./actions";
vi.mock("./actions", () => ({ loadBoardAction: vi.fn() }));
vi.mock("./use-board-column-order", () => ({ useBoardColumnOrder: (_id: string, board: unknown) => ({ board, locked: true, structureLocked: true }) }));
vi.mock("@/features/jobs/drafts/pipeline/delivery-actions", () => ({ loadDeliveryStatusAction: vi.fn(async () => ({ ok: false })) }));
beforeEach(() => { vi.clearAllMocks(); vi.stubGlobal("PointerEvent", MouseEvent); });
afterEach(() => { cleanup(); vi.unstubAllGlobals(); });
it("one filter entry opens counted groups, applies live, removes chips, clears and returns keyboard focus", async () => {
  const board = boardFixture(); board.stages[2].kind = "in_process";
  board.substates = [{ id: "tech", name: "Entrevista técnica" }, { id: "offer", name: "Oferta" }];
  board.participations[0].stage_id = board.stages[2].id;
  board.participations[0].substate_id = "tech";
  vi.mocked(loadBoardAction).mockResolvedValue({ ok: true, data: board });
  render(<MovementBoard vacancyId="vacancy" />);
  const trigger = await screen.findByRole("button", { name: "Filtros" });
  expect(screen.queryByRole("button", { name: /Subestados/ })).not.toBeInTheDocument();
  expect(screen.queryByRole("button", { name: "Limpiar filtros" })).not.toBeInTheDocument();
  fireEvent.click(trigger);
  const sheet = await screen.findByRole("dialog", { name: "Filtros" });
  expect(within(sheet).getByText("Combina varios valores; se muestran los candidatos que cumplen todos los grupos.")).toBeVisible();
  const group = within(sheet).getByRole("group", { name: "Subestado" });
  expect(within(sheet).getByRole("group", { name: "Columna" })).toBeVisible();
  const reasons = within(sheet).getByRole("group", { name: "Motivo de descarte" });
  expect(within(reasons).getByRole("group", { name: "Decisión de la empresa" })).toBeVisible();
  expect(within(reasons).getByRole("group", { name: "Decisión del candidato" })).toBeVisible();
  fireEvent.click(within(group).getByRole("checkbox", { name: "Sin subestado 0" }));
  expect(within(sheet).getByRole("button", { name: "Ver 0 candidatos" })).toBeVisible();
  fireEvent.click(within(group).getByRole("checkbox", { name: "Entrevista técnica 1" }));
  fireEvent.click(within(sheet).getByRole("button", { name: "Ver 1 candidatos" }));
  await waitFor(() => expect(trigger).toHaveFocus());
  expect(within(trigger).getByText("2")).toHaveAttribute("data-slot", "badge");
  expect(screen.getByText("Mostrando 1 de 1 candidatos")).toHaveAttribute("aria-live", "polite");
  fireEvent.click(screen.getByRole("button", { name: "Quitar Subestado: Entrevista técnica" }));
  expect(screen.getByText("Mostrando 0 de 1 candidatos")).toBeVisible();
  expect(screen.queryByRole("button", { name: "Ver detalle de Ana Pérez" })).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: "Limpiar filtros" }));
  expect(screen.getByRole("button", { name: "Ver detalle de Ana Pérez" })).toBeVisible();
  fireEvent.click(trigger);
  fireEvent.click(await screen.findByRole("checkbox", { name: "Oferta 0" }));
  fireEvent.click(screen.getByRole("button", { name: "Limpiar" }));
  expect(screen.getByRole("checkbox", { name: "Oferta 0" })).not.toBeChecked();
  fireEvent.keyDown(screen.getByRole("dialog"), { key: "Escape" });
  await waitFor(() => expect(trigger).toHaveFocus());
  expect(loadBoardAction).toHaveBeenCalledTimes(1);
});
it("column OR and discard groups combine live with other dimensions using full-board counts", async () => {
  const board = boardFixture(); board.stages[2].kind = "in_process";
  board.substates = [{ id: "tech", name: "Técnica" }];
  const item = { ...board.participations[0], stage_id: "interview", substate_id: "tech" };
  board.participations = [item, { ...item, id: "discarded", stage_id: "exit", substate_id: null, discard: { reason: { group: "candidate", key: "other" }, previous_stage_id: "interview", discarded_at: item.moved_at } }];
  vi.mocked(loadBoardAction).mockResolvedValue({ ok: true, data: board });
  render(<MovementBoard vacancyId="vacancy" />);
  fireEvent.click(await screen.findByRole("button", { name: "Filtros" }));
  const sheet = await screen.findByRole("dialog", { name: "Filtros" });
  const columns = within(sheet).getByRole("group", { name: "Columna" });
  within(columns).getAllByRole("checkbox").forEach((option, index) => {
    const stage = [...board.stages, board.exit][index];
    expect(option).toHaveAccessibleName(`${stage.name} ${board.participations.filter(item => item.stage_id === stage.id).length}`);
  });
  fireEvent.click(within(sheet).getByRole("checkbox", { name: "Técnica 1" }));
  fireEvent.click(within(columns).getByRole("checkbox", { name: "Revisión 0" }));
  expect(within(sheet).getByRole("button", { name: "Ver 0 candidatos" })).toBeVisible();
  fireEvent.click(within(columns).getByRole("checkbox", { name: "Entrevista 1" }));
  expect(within(sheet).getByRole("button", { name: "Ver 1 candidatos" })).toBeVisible();
  fireEvent.click(within(sheet).getByRole("button", { name: "Limpiar" }));
  const company = within(sheet).getByRole("group", { name: "Decisión de la empresa" });
  const candidate = within(sheet).getByRole("group", { name: "Decisión del candidato" });
  fireEvent.click(within(company).getByRole("checkbox", { name: "Otro 0" }));
  expect(within(sheet).getByRole("button", { name: "Ver 0 candidatos" })).toBeVisible();
  fireEvent.click(within(candidate).getByRole("checkbox", { name: "Otro 1" }));
  expect(within(sheet).getByRole("button", { name: "Ver 1 candidatos" })).toBeVisible();
  fireEvent.click(within(columns).getByRole("checkbox", { name: "Entrevista 1" }));
  expect(within(sheet).getByRole("button", { name: "Ver 0 candidatos" })).toBeVisible();
  fireEvent.click(within(columns).getByRole("checkbox", { name: "Descartados 1" }));
  fireEvent.click(within(sheet).getByRole("button", { name: "Ver 1 candidatos" }));
  await waitFor(() => expect(screen.getByRole("button", { name: "Quitar Motivo de descarte: Decisión del candidato · Otro" })).toBeVisible());
});
