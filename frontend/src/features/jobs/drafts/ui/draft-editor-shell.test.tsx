import * as React from "react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, within, waitFor } from "@testing-library/react";
import "@testing-library/jest-dom/vitest";
import { LocalDraftForm } from "./local-draft-form";
import { saveDraftV2Action } from "../actions";
import { loadDraftPublicationAction } from "../pipeline/publication-actions";
import { createDraftModel } from "../model";
vi.mock("../actions", () => ({ saveDraftV2Action: vi.fn() }));
vi.mock("../pipeline/publication-actions", () => ({ loadDraftPublicationAction: vi.fn(), publishDraftAction: vi.fn() }));
vi.mock("../requesters/actions", () => ({ searchRequestersAction: vi.fn(async () => ({ ok: true, items: [], nextCursor: null })), createRequesterAction: vi.fn() }));
vi.mock("sileo", () => ({ sileo: { success: vi.fn(), error: vi.fn(), dismiss: vi.fn() } }));
vi.mock("@/features/geo/use-geo-catalog", () => ({ useGeoCatalog: () => ({ countries: { status: "success", data: { items: [] } }, states: { status: "success", data: { items: [] } }, municipalities: { status: "success", data: { items: [] } } }), useGeoPostalCode: () => ({ status: "idle" }) }));
const nav = (name: string) => within(screen.getByRole("navigation", { name: "Secciones de la vacante" })).getByRole("button", { name });
const save = () => screen.getByRole("button", { name: /^Guardar (borrador|cambios)$/ });
beforeEach(() => {
  vi.mocked(saveDraftV2Action).mockResolvedValue({ ok: true, draftId: "saved", etag: '"v1"', version: "1", savedAt: "2026-10-06T03:00:00Z" });
  vi.mocked(loadDraftPublicationAction).mockResolvedValue({ ok: true, publication: { status: "draft", publishedAt: null, missing: [] } });
});
afterEach(() => { cleanup(); vi.clearAllMocks(); });
it("freely navigates while keeping the same mounted input and its value", () => {
  render(<LocalDraftForm />);
  const title = screen.getByRole("textbox", { name: "Título" });
  fireEvent.change(title, { target: { value: "Mi oportunidad" } });
  fireEvent.click(nav("Preguntas de filtro"));
  expect(title).toBeInTheDocument(); expect(title).not.toBeVisible();
  expect(screen.getByText("4 de 5")).toBeVisible();
  fireEvent.click(nav("Información básica"));
  expect(screen.getByRole("textbox", { name: "Título" })).toBe(title);
  expect(title).toHaveValue("Mi oportunidad");
});
it("counts readiness rather than visited sections and discloses unknown server requirements", () => {
  render(<LocalDraftForm />);
  const progress = screen.getByRole("progressbar", { name: "Lista para publicar" });
  const before = progress.getAttribute("aria-valuenow");
  fireEvent.click(nav("Revisión y publicación"));
  expect(progress).toHaveAttribute("aria-valuenow", before);
  fireEvent.click(nav("Información básica"));
  fireEvent.change(screen.getByRole("textbox", { name: "Título" }), { target: { value: "Backend" } });
  expect(Number(progress.getAttribute("aria-valuenow"))).toBeGreaterThan(Number(before));
  expect(screen.getByText(/Solicitud y entrega aún no comprobadas/)).toBeVisible();
  expect(nav("Información básica")).not.toHaveAttribute("data-complete", "true");
});
it("saves from any section and routes invalid values to the first field", async () => {
  render(<LocalDraftForm />);
  const title = screen.getByRole("textbox", { name: "Título" });
  fireEvent.change(title, { target: { value: "x".repeat(201) } });
  fireEvent.click(nav("Compensación y beneficios")); fireEvent.click(save());
  await waitFor(() => expect(title).toHaveFocus());
  expect(title).toHaveAttribute("aria-invalid", "true");
  expect(saveDraftV2Action).not.toHaveBeenCalled();
  fireEvent.change(title, { target: { value: "Backend" } });
  fireEvent.click(nav("Preguntas de filtro")); fireEvent.click(save());
  await waitFor(() => expect(saveDraftV2Action).toHaveBeenCalledOnce());
});
it("keeps explicit save status and publish controls in the sticky bar", async () => {
  const { container } = render(<LocalDraftForm />);
  const footer = container.querySelector('[data-pf-draft-save-bar]')!;
  expect(footer).toHaveClass("sticky", "bottom-0");
  expect(footer).toHaveTextContent("Sin guardado automático");
  fireEvent.change(screen.getByRole("textbox", { name: "Título" }), { target: { value: "Backend" } });
  expect(footer).toHaveTextContent("Cambios sin guardar");
  fireEvent.click(within(footer as HTMLElement).getByRole("button", { name: "Publicar vacante" }));
  expect(footer).toHaveTextContent("Guarda los cambios antes de publicar");
  fireEvent.click(save());
  await waitFor(() => expect(footer).toHaveTextContent("Guardado · versión 1"));
});
it("opens the mobile public preview in a composed Sheet without private data", async () => {
  const model = createDraftModel(); model.requesterName = "Cliente secreto";
  model.fields.compensation = { mode: "fixed", amount: "987654.32", min: null, max: null, currency: "MXN", pay_period: "monthly", basis: "gross", public_visible: false };
  const { container } = render(<LocalDraftForm initialModel={model} initialScreeningQuestionsV2={[]} />);
  expect(container.querySelector('[data-pf-live-preview]')).toHaveClass("hidden", "xl:block");
  fireEvent.click(screen.getByRole("button", { name: "Vista previa" }));
  const dialog = await screen.findByRole("dialog", { name: "Vista previa pública" });
  expect(dialog).toHaveAttribute("data-slot", "sheet-content");
  expect(dialog.querySelector('[data-slot="sheet-header"] [data-slot="sheet-title"]')).not.toBeNull();
  expect(dialog).toHaveTextContent("Salario no publicado");
  expect(dialog).not.toHaveTextContent("Cliente secreto"); expect(dialog).not.toHaveTextContent("987654");
  expect(dialog.querySelector('[data-pf-draft-internal]')).toBeNull();
});
it("confirms ordinary in-app links without intercepting same-page anchors or new tabs", async () => {
  const follow = vi.fn();
  render(<><a href="/empresa/vacantes" onClick={event => { event.preventDefault(); follow(); }}>Volver</a><a href="/empresa/vacantes" target="_blank" onClick={event => event.preventDefault()}>Otra pestaña</a><a href="#draft-location">Ubicación</a><LocalDraftForm /></>);
  fireEvent.change(screen.getByRole("textbox", { name: "Título" }), { target: { value: "Backend" } });
  fireEvent.click(screen.getByRole("link", { name: "Ubicación" }));
  fireEvent.click(screen.getByRole("link", { name: "Otra pestaña" }));
  expect(screen.queryByRole("alertdialog")).toBeNull();
  fireEvent.click(screen.getByRole("link", { name: "Volver" }));
  const dialog = await screen.findByRole("alertdialog", { name: "¿Salir sin guardar?" });
  expect(dialog).toHaveTextContent("Perderás los cambios que no guardaste.");
  expect(within(dialog).getByRole("button", { name: "Salir sin guardar" })).toHaveClass("text-destructive");
  fireEvent.click(within(dialog).getByRole("button", { name: "Cancelar" }));
  expect(screen.getByRole("textbox", { name: "Título" })).toHaveValue("Backend");
  expect(follow).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole("link", { name: "Volver" }));
  fireEvent.click(within(await screen.findByRole("alertdialog")).getByRole("button", { name: "Salir sin guardar" }));
  expect(follow).toHaveBeenCalledOnce();
});
it("blocks unload only with unsaved edits and removes the guard after saving", async () => {
  render(<LocalDraftForm />);
  const unload = () => { const e = new Event("beforeunload", { cancelable: true }); window.dispatchEvent(e); return e; };
  expect(unload().defaultPrevented).toBe(false);
  fireEvent.change(screen.getByRole("textbox", { name: "Título" }), { target: { value: "Backend" } });
  expect(unload().defaultPrevented).toBe(true);
  fireEvent.click(save()); await waitFor(() => expect(save()).toHaveTextContent("Guardar cambios"));
  expect(unload().defaultPrevented).toBe(false);
});
