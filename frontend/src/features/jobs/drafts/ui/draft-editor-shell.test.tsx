  expect(dialog.querySelector('[data-slot="skeleton"]')).toBeNull();
  expect(dialog).not.toHaveTextContent("Empresa no disponible");
  fireEvent.focus(window);
  expect(loadCompanyStateAction).toHaveBeenCalledTimes(1);
