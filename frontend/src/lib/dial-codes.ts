export const DIAL_CODES: readonly DialCode[] = [...countries].sort((a, b) =>
  a.country === "MX" ? -1 : b.country === "MX" ? 1 : a.name.localeCompare(b.name, "es"));

// Shared plans need a predictable display when the API only supplies a dial.
const preferredCountries: Readonly<Record<string, string>> = { "+1": "US", "+7": "RU", "+44": "GB", "+52": "MX" };
export function countryForDial(dial: string): DialCode | null {
  return DIAL_CODES.find(item => item.dial === dial && item.country === preferredCountries[dial])
    ?? DIAL_CODES.find(item => item.dial === dial) ?? null;
}
