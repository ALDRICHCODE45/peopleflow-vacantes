// Package languages owns the embedded profile vocabularies. It has no external
// dependencies. Codes are opaque, stable identifiers, not language-family hints.
package languages

import "slices"

// Item is the public language catalog representation.
type Item struct {
	Code string `json:"code"`
	Name string `json:"name"`
}

// All returns a defensive copy. Presentation ordering belongs to the HTTP layer.
func All() []Item { return slices.Clone(catalog) }

// Lookup is exact: codes are never trimmed or case-folded.
func Lookup(code string) (string, bool) {
	for _, item := range catalog {
		if item.Code == code {
			return item.Name, true
		}
	}
	return "", false
}

