// Package cvs owns the private candidate CV library and storage ports.
package cvs

import (
	"context"
	"io"
	"time"

	"github.com/google/uuid"
)

type CV struct {
	ID          uuid.UUID `json:"id"`
	Name        string    `json:"name"`
	Size        int64     `json:"size"`
	ContentType string    `json:"content_type"`
	UploadedAt  time.Time `json:"uploaded_at"`
	InUse       bool      `json:"in_use"`
}
type Limits struct {
	MaxCVs       int      `json:"max_cvs"`
	MaxBytes     int      `json:"max_bytes"`
	ContentTypes []string `json:"content_types"`
}
type Page struct {
	Items  []CV   `json:"items"`
	Limits Limits `json:"limits"`
}

func NewPage(items []CV) Page {
	if items == nil {
		items = []CV{}
	}
	return Page{items, Limits{MaxCVs, MaxBytes, []string{PDF, DOCX}}}
}

// Storage keys are generated by the adapter, never derived from user input.
// All objects are private. Implementations must reject noncanonical keys.
type Storage interface {
	Put(context.Context, []byte) (string, error)
	Open(context.Context, string) (io.ReadCloser, error)
	Delete(context.Context, string) error
	Keys(context.Context) ([]string, error)
}

// Library owns file-first/row-second writes and cleanup. Reconcile and Upload
// must serialize across processes so reconciliation cannot delete in-flight files.
// Subject always comes from verified auth context, never a request parameter.
type Library interface {
	List(context.Context, string) ([]CV, error)
	Upload(context.Context, string, string, string, []byte) (CV, error)
	Rename(context.Context, string, uuid.UUID, string) (CV, error)
	Remove(context.Context, string, uuid.UUID) error
	File(context.Context, string, uuid.UUID) (CV, io.ReadCloser, error)
}
